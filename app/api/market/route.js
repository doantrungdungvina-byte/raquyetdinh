function average(values) {
  const good = values.filter(Number.isFinite);
  return good.length ? good.reduce((a, b) => a + b, 0) / good.length : null;
}
function sma(values, period) {
  return values.map((_, i) => i + 1 < period ? null : average(values.slice(i + 1 - period, i + 1)));
}
function rsi(values, period = 14) {
  if (values.length <= period) return null;
  let gains = 0, losses = 0;
  for (let i = 1; i <= period; i++) {
    const diff = values[i] - values[i - 1];
    if (diff >= 0) gains += diff; else losses -= diff;
  }
  let avgGain = gains / period, avgLoss = losses / period;
  for (let i = period + 1; i < values.length; i++) {
    const diff = values[i] - values[i - 1];
    avgGain = (avgGain * (period - 1) + Math.max(diff, 0)) / period;
    avgLoss = (avgLoss * (period - 1) + Math.max(-diff, 0)) / period;
  }
  if (avgLoss === 0) return 100;
  return 100 - 100 / (1 + avgGain / avgLoss);
}
function round(n) { return Number.isFinite(n) ? Number(n.toFixed(4)) : null; }
function ema(values, period) {
  if (values.length < period) return null;
  const k = 2 / (period + 1);
  let out = average(values.slice(0, period));
  for (let i = period; i < values.length; i++) out = values[i] * k + out * (1 - k);
  return out;
}

function emptyFundamentals() {
  return {
    pe: null,
    pb: null,
    eps: null,
    dividendPerShare: null,
    dividendYield: null,
    source: null,
    updatedAt: null,
    status: "unavailable",
  };
}

// Reads the snapshot generated by the scheduled Python/Vnstock job.
// Expected file: public/data/fundamentals.json
// Expected shape: { "FPT": { "pe": 15.2, "pb": 3.1, ... } }
async function getFundamentals(request, symbol, kind) {
  if (kind !== "stock") return emptyFundamentals();

  try {
    const dataUrl = new URL("/data/fundamentals.json", request.url);
    const response = await fetch(dataUrl, {
      headers: { Accept: "application/json" },
      signal: AbortSignal.timeout(3000),
      next: { revalidate: 3600 },
    });
    if (!response.ok) return emptyFundamentals();

    const payload = await response.json();
    const raw = payload?.[symbol] ?? payload?.data?.[symbol] ?? null;
    if (!raw || typeof raw !== "object") return emptyFundamentals();

    const numeric = (value) => {
      if (value === null || value === undefined || value === "") return null;
      const parsed = Number(value);
      return Number.isFinite(parsed) ? parsed : null;
    };

    const result = {
      pe: numeric(raw.pe ?? raw.trailingPE ?? raw.trailing_pe),
      pb: numeric(raw.pb ?? raw.priceToBook ?? raw.price_to_book),
      eps: numeric(raw.eps ?? raw.eps_ttm),
      dividendPerShare: numeric(raw.dividendPerShare ?? raw.dividend_per_share ?? raw.dividendRate),
      dividendYield: numeric(raw.dividendYield ?? raw.dividend_yield),
      source: typeof raw.source === "string" ? raw.source : "Vnstock snapshot",
      updatedAt: typeof raw.updatedAt === "string" ? raw.updatedAt : (typeof raw.updated_at === "string" ? raw.updated_at : null),
      status: "partial",
    };

    // Accept either decimal yield (0.035) or percentage (3.5), return percentage.
    if (result.dividendYield !== null && result.dividendYield > 0 && result.dividendYield <= 1) {
      result.dividendYield *= 100;
    }
    if ([result.pe, result.pb, result.eps, result.dividendPerShare, result.dividendYield].some(v => v !== null)) {
      result.status = "available";
    }
    return result;
  } catch {
    return emptyFundamentals();
  }
}

export async function GET(request) {
  const { searchParams } = new URL(request.url);
  const symbol = (searchParams.get("symbol") || "FPT").trim().toUpperCase();
  const kind = (searchParams.get("kind") || "stock").trim().toLowerCase();

  if (!/^[A-Z0-9^=.-]{1,20}$/.test(symbol)) {
    return NextResponse.json({ error: "Mã tài sản không hợp lệ." }, { status: 400 });
  }
  if (!['stock', 'forex', 'crypto'].includes(kind)) {
    return NextResponse.json({ error: "Loại tài sản không hợp lệ." }, { status: 400 });
  }

  // Yahoo thường dùng hậu tố .VN cho cổ phiếu Việt Nam, nhưng không có đủ mã
  // HNX/UPCoM. Thử các biến thể lần lượt để một mã không được hỗ trợ không dừng ngay.
  const yahooSymbols = kind === "forex" || kind === "crypto"
    ? [FX[symbol] || symbol]
    : [`${symbol}.VN`, `${symbol}.HN`, `${symbol}.UPCOM`, symbol];
  let yahooSymbol = yahooSymbols[0];
  let result = null;
  let lastHttpStatus = null;

  try {
    for (const candidate of yahooSymbols) {
      const url = `https://query1.finance.yahoo.com/v8/finance/chart/${encodeURIComponent(candidate)}?range=2y&interval=1d&events=history`;
      try {
        const response = await fetch(url, {
          headers: { "User-Agent": "Mozilla/5.0 TradingTools/1.0", Accept: "application/json" },
          next: { revalidate: 300 },
        });
        lastHttpStatus = response.status;
        if (!response.ok) continue;
        const payload = await response.json();
        const candidateResult = payload?.chart?.result?.[0];
        if (candidateResult?.timestamp?.length) {
          yahooSymbol = candidate;
          result = candidateResult;
          break;
        }
      } catch {
        // Try the next symbol format if a candidate is unavailable.
      }
    }
    if (!result) {
      // Yahoo does not cover every HNX/UPCoM ticker. Fall back to the project's
      // Python Vnstock function (VCI -> KBS) before returning an error.
      try {
        const fallbackUrl = new URL("/api/vnstock", request.url);
        fallbackUrl.searchParams.set("symbol", symbol);
        const fallbackResponse = await fetch(fallbackUrl, {
          headers: { Accept: "application/json" },
          cache: "no-store",
          signal: AbortSignal.timeout(20000),
        });
        const fallback = await fallbackResponse.json().catch(() => null);
        if (fallbackResponse.ok && fallback && Number.isFinite(Number(fallback.price))) {
          const close = Number(fallback.price);
          const previousClose = Number(fallback.previousClose);
          const indicators = fallback.indicators || {};
          const history = Array.isArray(fallback.history) ? fallback.history : [];
          const ma20 = Number(indicators.ma20);
          const ma50 = Number(indicators.ma50);
          const trend = Number.isFinite(ma20) && close > ma20 && (!Number.isFinite(ma50) || ma20 > ma50)
            ? "Tăng"
            : Number.isFinite(ma20) && close < ma20 && (!Number.isFinite(ma50) || ma20 < ma50)
              ? "Giảm" : "Đi ngang / chưa rõ";
          return NextResponse.json({
            symbol,
            yahooSymbol: null,
            currency: "VND",
            price: close,
            changePct: Number.isFinite(Number(fallback.changePct)) ? Number(fallback.changePct) : null,
            indicators: {
              ma20: Number.isFinite(ma20) ? ma20 : null,
              ma50: Number.isFinite(ma50) ? ma50 : null,
              ma200: Number.isFinite(Number(indicators.ma200)) ? Number(indicators.ma200) : null,
              rsi14: Number.isFinite(Number(indicators.rsi14)) ? Number(indicators.rsi14) : null,
              atr14: Number.isFinite(Number(indicators.atr14)) ? Number(indicators.atr14) : null,
              atrPct: Number.isFinite(Number(indicators.atr14)) && close ? Number((Number(indicators.atr14) / close * 100).toFixed(4)) : null,
              macd: Number.isFinite(Number(indicators.macd)) ? Number(indicators.macd) : null,
              bollingerUpper: Number.isFinite(Number(indicators.bollingerUpper)) ? Number(indicators.bollingerUpper) : null,
              bollingerLower: Number.isFinite(Number(indicators.bollingerLower)) ? Number(indicators.bollingerLower) : null,
              support20: history.length ? Math.min(...history.slice(-20).map(r => Number(r.low)).filter(Number.isFinite)) : null,
              resistance20: history.length ? Math.max(...history.slice(-20).map(r => Number(r.high)).filter(Number.isFinite)) : null,
            },
            analysis: {
              trend,
              technicalSummary: [
                "Nguồn dữ liệu: Vnstock (ưu tiên VCI, dự phòng KBS).",
                "Các chỉ báo kỹ thuật được tính từ lịch sử giá do nguồn trả về.",
              ],
            },
            fundamentals: emptyFundamentals(),
            levels: Array.isArray(fallback.levels) ? fallback.levels : [],
            history: history.filter(r => Number.isFinite(Number(r.close))).slice(-220).map(r => ({ date: r.date, close: Number(r.close) })),
            source: fallback.source || "Vnstock",
            updatedAt: fallback.asOf || fallback.updatedAt || new Date().toISOString(),
          }, { headers: { "Cache-Control": "s-maxage=300, stale-while-revalidate=600" } });
        }
      } catch {
        // Keep the original Yahoo error below, with the fallback failure explained.
      }

      // Last-resort fallback for Vietnamese stocks: TradingView scanner.
      // This provides a current quote and technical snapshot (not historical OHLCV).
      if (kind === "stock") {
        try {
          const exchanges = ["HNX", "HOSE", "UPCOM"];
          const tickers = exchanges.map(ex => `${ex}:${symbol}`);
          const tvResponse = await fetch("https://scanner.tradingview.com/vietnam/scan", {
            method: "POST",
            headers: { "Content-Type": "application/json", Accept: "application/json" },
            body: JSON.stringify({
              symbols: { tickers, query: { types: [] } },
              columns: [
                "close", "change", "Perf.W", "Perf.1M", "volume",
                "average_volume_10d_calc", "RSI", "EMA9", "EMA21", "EMA50",
                "EMA200", "MACD.macd", "MACD.signal", "BB.upper", "BB.lower",
                "ATR", "price_52_week_high", "price_52_week_low", "name"
              ]
            }),
            signal: AbortSignal.timeout(12000),
            cache: "no-store",
          });
          if (tvResponse.ok) {
            const tvPayload = await tvResponse.json();
            const tvRows = Array.isArray(tvPayload?.data) ? tvPayload.data : [];
            const tvRow = tvRows.find(row => row?.d && Number.isFinite(Number(row.d[0])));
            if (tvRow) {
              const d = tvRow.d;
              const tvNum = value => value === null || value === undefined || value === "" ? null : (Number.isFinite(Number(value)) ? Number(value) : null);
              const close = tvNum(d[0]);
              const changePct = tvNum(d[1]);
              const volume = tvNum(d[4]);
              const avgVolume10 = tvNum(d[5]);
              const rsi14 = tvNum(d[6]);
              const ema9 = tvNum(d[7]);
              const ema21 = tvNum(d[8]);
              const ma50 = tvNum(d[9]);
              const ma200 = tvNum(d[10]);
              const macd = tvNum(d[11]);
              const macdSignal = tvNum(d[12]);
              const bbUpper = tvNum(d[13]);
              const bbLower = tvNum(d[14]);
              const atr = tvNum(d[15]);
              const high52 = tvNum(d[16]);
              const low52 = tvNum(d[17]);
              const trend = ema9 !== null && ema21 !== null && ma50 !== null && ma200 !== null
                ? (ema9 > ema21 && ema21 > ma50 && ma50 > ma200 ? "Tăng"
                  : ema9 < ema21 && ema21 < ma50 && ma50 < ma200 ? "Giảm" : "Đi ngang / chưa rõ")
                : "Đi ngang / chưa rõ";
              const technicalSummary = [
                `Nguồn dữ liệu: TradingView Scanner (${tvRow.s || "mã cổ phiếu Việt Nam"}).`,
                trend === "Tăng" ? "EMA9 > EMA21 > EMA50 > EMA200: xu hướng kỹ thuật nghiêng tăng." :
                  trend === "Giảm" ? "EMA9 < EMA21 < EMA50 < EMA200: xu hướng kỹ thuật nghiêng giảm." :
                  "Các đường EMA chưa đồng thuận rõ ràng.",
                rsi14 !== null && rsi14 >= 70 ? "RSI đang ở vùng quá mua." :
                  rsi14 !== null && rsi14 <= 30 ? "RSI đang ở vùng quá bán." : "RSI chưa ở vùng cực đoan hoặc không có dữ liệu.",
                "TradingView Scanner chỉ cung cấp ảnh chụp chỉ báo; lịch sử giá không có trong nguồn dự phòng này."
              ];
              const levels = [
                { label: "Giảm 3%", price: round(close * 0.97), basis: "Giá hiện tại -3%", dropPct: 3 },
                { label: "Giảm 6%", price: round(close * 0.94), basis: "Giá hiện tại -6%", dropPct: 6 },
                { label: "Giảm 10%", price: round(close * 0.90), basis: "Giá hiện tại -10%", dropPct: 10 },
              ];
              return NextResponse.json({
                symbol,
                yahooSymbol: null,
                currency: "VND",
                price: round(close),
                changePct: round(changePct),
                indicators: {
                  ma20: null, ma50: round(ma50), ma200: round(ma200), rsi14: round(rsi14),
                  atr14: round(atr), atrPct: atr !== null && close ? round(atr / close * 100) : null,
                  macd: round(macd), bollingerUpper: round(bbUpper), bollingerLower: round(bbLower),
                  support20: round(low52), resistance20: round(high52),
                  ema9: round(ema9), ema21: round(ema21),
                  volume, averageVolume10: avgVolume10,
                  volumeVsAvgPct: volume !== null && avgVolume10 ? round((volume / avgVolume10 - 1) * 100) : null,
                  weeklyChangePct: round(tvNum(d[2])), monthlyChangePct: round(tvNum(d[3])),
                },
                analysis: { trend, technicalSummary },
                fundamentals: emptyFundamentals(),
                levels,
                history: [],
                source: "TradingView Scanner",
                updatedAt: new Date().toISOString(),
                note: "Nguồn dự phòng chỉ có giá/chỉ báo hiện tại; không có lịch sử OHLCV."
              }, { headers: { "Cache-Control": "s-maxage=300, stale-while-revalidate=600" } });
            }
          }
        } catch {
          // Preserve the Yahoo/Vnstock failure details if TradingView also fails.
        }
      }
      throw new Error(`Yahoo Finance không có dữ liệu cho ${symbol} (đã thử ${yahooSymbols.join(", ")}${lastHttpStatus ? `; HTTP cuối: ${lastHttpStatus}` : ""}); nguồn dự phòng Vnstock cũng không trả dữ liệu. Kiểm tra cấu hình Python/Vnstock trên Vercel.`);
    }

    const q = result.indicators?.quote?.[0] || {};
    const rows = result.timestamp.map((time, i) => ({
      date: new Date(time * 1000).toISOString().slice(0, 10),
      open: q.open?.[i],
      high: q.high?.[i],
      low: q.low?.[i],
      close: q.close?.[i],
      volume: q.volume?.[i] || 0,
    })).filter(r => [r.open, r.high, r.low, r.close].every(Number.isFinite));

    if (rows.length < 20) throw new Error(`Dữ liệu lịch sử của ${symbol} quá ít để phân tích.`);

    const closes = rows.map(r => r.close);
    const last = rows.at(-1), prev = rows.at(-2);
    const ma20 = average(closes.slice(-20));
    const ma50 = closes.length >= 50 ? average(closes.slice(-50)) : null;
    const ma200 = closes.length >= 200 ? average(closes.slice(-200)) : null;
    const stdVals = closes.slice(-20);
    const stdMean = average(stdVals);
    const std = Math.sqrt(average(stdVals.map(v => (v - stdMean) ** 2)));
    const trueRanges = rows.slice(-15).map((r, i) => {
      const prevClose = rows[rows.length - 15 + i - 1]?.close ?? r.close;
      return Math.max(r.high - r.low, Math.abs(r.high - prevClose), Math.abs(r.low - prevClose));
    });
    const atr = average(trueRanges.slice(1));
    const highN = n => Math.max(...rows.slice(-n).map(r => r.high));
    const lowN = n => Math.min(...rows.slice(-n).map(r => r.low));
    const ema12 = ema(closes, 12), ema26 = ema(closes, 26);
    const macd = ema12 != null && ema26 != null ? ema12 - ema26 : null;
    const bbUpper = ma20 + 2 * std, bbLower = ma20 - 2 * std;
    const rsi14 = rsi(closes);
    const trend = last.close > ma20 && ma20 > (ma50 ?? ma20) ? "Tăng" : last.close < ma20 && ma20 < (ma50 ?? ma20) ? "Giảm" : "Đi ngang / chưa rõ";
    const technicalSummary = [
      trend === "Tăng" ? "Giá trên MA20 và MA20 trên MA50: xu hướng ngắn-trung hạn nghiêng tăng." : trend === "Giảm" ? "Giá dưới MA20 và MA20 dưới MA50: xu hướng ngắn-trung hạn nghiêng giảm." : "Các đường trung bình chưa đồng thuận; ưu tiên chờ xác nhận.",
      rsi14 >= 70 ? "RSI vào vùng quá mua, tránh mua đuổi và chờ tín hiệu xác nhận." : rsi14 <= 30 ? "RSI vào vùng quá bán; có thể xuất hiện hồi kỹ thuật nhưng chưa đồng nghĩa đảo chiều." : "RSI chưa ở vùng cực đoan.",
      last.close >= bbUpper ? "Giá chạm/vượt Bollinger trên: biến động mạnh, rủi ro hồi lại tăng." : last.close <= bbLower ? "Giá chạm/dưới Bollinger dưới: theo dõi phản ứng tại vùng hỗ trợ." : "Giá nằm trong dải Bollinger."
    ];

    const candidates = [
      { label: "Mua thăm dò", price: ma20, basis: "MA20" },
      { label: "DCA 1", price: ma50, basis: "MA50" },
      { label: "Bollinger Lower", price: ma20 - 2 * std, basis: "Bollinger Lower" },
      { label: "DCA 3", price: ma200, basis: "MA200" },
      { label: "Hỗ trợ 20D", price: lowN(20), basis: "Low 20D" },
      { label: "Hỗ trợ 50D", price: lowN(Math.min(50, rows.length)), basis: "Low 50D" },
      { label: "ATR 1", price: last.close - .75 * atr, basis: "0.75 ATR" },
      { label: "ATR 2", price: last.close - 1.5 * atr, basis: "1.50 ATR" },
      { label: "ATR 3", price: last.close - 2.5 * atr, basis: "2.50 ATR" },
    ].filter(x => Number.isFinite(x.price) && x.price > 0 && x.price < last.close * 1.005)
      .sort((a, b) => b.price - a.price);

    const levels = [];
    for (const item of candidates) {
      if (!levels.some(x => Math.abs(x.price - item.price) / last.close < .012)) {
        levels.push({ ...item, price: round(item.price), dropPct: round((1 - item.price / last.close) * 100) });
      }
    }

    const fundamentals = await getFundamentals(request, symbol, kind);
    const currency = kind === "stock" ? "VND" : "USD";

    return NextResponse.json({
      symbol,
      yahooSymbol,
      currency,
      price: round(last.close),
      changePct: round((last.close / prev.close - 1) * 100),
      indicators: {
        ma20: round(ma20), ma50: round(ma50), ma200: round(ma200), rsi14: round(rsi14),
        atr14: round(atr), atrPct: round(atr / last.close * 100),
        macd: round(macd), bollingerUpper: round(bbUpper), bollingerLower: round(bbLower),
        support20: round(lowN(20)), resistance20: round(highN(20)),
      },
      analysis: { trend, technicalSummary },
      fundamentals,
      levels,
      history: rows.slice(-220).map(r => ({ date: r.date, close: r.close })),
      source: "Yahoo Finance",
      updatedAt: last.date,
    }, { headers: { "Cache-Control": "s-maxage=300, stale-while-revalidate=600" } });
  } catch (error) {
    return NextResponse.json({ error: error.message || "Không lấy được dữ liệu." }, { status: 502 });
  }
}
